# Now that we have the subgroups identified we can use limma to find DEGs
design <- model.matrix(~ 0 + clusters + project, data = metadata)

colnames(design) <- c(levels(metadata$clusters), levels(metadata$project)[-1])

fit <- lmFit(original_corrected, design)

contrast_matrix <- makeContrasts(
  TYR_vs_SHH = TYR - SHH,
  MYC_vs_SHH = MYC - SHH,
  TYR_vs_MYC = TYR - MYC,
  levels = design
)

fit2 <- contrasts.fit(fit, contrast_matrix)
fit2 <- eBayes(fit2)

top_all <- topTable(fit2, adjust.method="fdr", number=Inf) %>%
  arrange(desc(F)) %>%
  filter(F > 20)

write.csv(top_all, file = "results/degs_original_f20.csv")
