# Function create PCA
plot_pca <- function(top_scaled, metadata) {
  pca <- prcomp(t(top_scaled), scale = TRUE)

  pca_var <- pca$sdev^2

  pca_var_percent <- round(pca_var/sum(pca_var)*100, 1)

  pca_data <- data.frame(ind = rownames(pca$x),
    pc1 = pca$x[, 1],
    pc2 = pca$x[, 2]
  ) %>%
    inner_join(., metadata, by = "ind")

  ggplot(data = pca_data, aes(x = pc1, y = pc2, color = project))+
    geom_point()+
    xlab(paste("PC1 - ", pca_var_percent[1], "%"))+
    ylab(paste("PC2 - ", pca_var_percent[2], "%"))+
    ggtitle("PCA")

}

clustering <- function(top_scaled) {
  # Compute correlation distance
  dist_matrix <- as.dist(1 - cor(top_scaled, method = "pearson"))

  # Hierarchical clustering
  hc <- hclust(dist_matrix, method = "average")

  # Dendrogram plot
  plot(as.dendrogram(hc, hang = 1, label = NULL), yaxt = "n")
  rect.hclust(hc, k = 3, border = "red")

  clusters <- cutree(hc, k = 3)

  # Original cluster was 22/23/22
  table(clusters)

  clusters
}

